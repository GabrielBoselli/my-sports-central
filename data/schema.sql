CREATE TABLE IF NOT EXISTS games (
    game_id TEXT PRIMARY KEY,
    game_date TEXT,
    season TEXT,
    season_type TEXT,
    home_team_id INTEGER,
    away_team_id INTEGER,
    home_team_tricode TEXT,
    away_team_tricode TEXT,
    home_score INTEGER,
    away_score INTEGER,
    home_win INTEGER,
    total_points INTEGER,
    is_playoff INTEGER
);

CREATE TABLE IF NOT EXISTS team_game_stats (
    game_id TEXT,
    team_id INTEGER,
    is_home INTEGER,
    fgm INTEGER,
    fga INTEGER,
    fg_pct REAL,
    fg3m INTEGER,
    fg3a INTEGER,
    fg3_pct REAL,
    ftm INTEGER,
    fta INTEGER,
    ft_pct REAL,
    oreb INTEGER,
    dreb INTEGER,
    reb INTEGER,
    ast INTEGER,
    stl INTEGER,
    blk INTEGER,
    tov INTEGER,
    pts INTEGER,
    ts_pct REAL,
    pace REAL,
    PRIMARY KEY (game_id, team_id)
);

CREATE TABLE IF NOT EXISTS game_features (
    game_id TEXT PRIMARY KEY,
    home_team_id INTEGER,
    away_team_id INTEGER,
    home_last10_winrate REAL,
    away_last10_winrate REAL,
    home_last10_net_rating REAL,
    away_last10_net_rating REAL,
    home_last10_avg_pts REAL,
    away_last10_avg_pts REAL,
    home_last10_avg_pts_allowed REAL,
    away_last10_avg_pts_allowed REAL,
    home_last10_ts_pct REAL,
    away_last10_ts_pct REAL,
    home_last10_pace REAL,
    away_last10_pace REAL,
    home_streak INTEGER,
    away_streak INTEGER,
    home_rest_days INTEGER,
    away_rest_days INTEGER,
    home_back_to_back INTEGER,
    away_back_to_back INTEGER,
    h2h_last5_home_wins INTEGER,
    h2h_last5_away_wins INTEGER,
    h2h_avg_total_pts REAL,
    playoff_game_number INTEGER,
    home_series_wins INTEGER,
    away_series_wins INTEGER,
    home_win INTEGER,
    total_points INTEGER,
    over_224 INTEGER
);